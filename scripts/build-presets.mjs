/**
 * Build src/model/preset-shapes.js, PowerPoint's preset shape geometry, from
 * presetShapeDefinitions.xml, and src/model/preset-warps.js, its WordArt text
 * warps, from presetTextWarpDefinitions.xml (the shape libraries that come
 * with the Office Open XML standard, ECMA-376 Part 1; LibreOffice keeps
 * copies in oox/source/drawingml/customshapes/ and oox/source/export/). Run
 * it when one of those files changes:
 *
 *   node scripts/build-presets.mjs path/to/presetShapeDefinitions.xml
 *   node scripts/build-presets.mjs path/to/presetTextWarpDefinitions.xml
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { JSDOM } from 'jsdom';
import { definitionFromXml } from '../src/model/geometry.js';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-presets.mjs presetShapeDefinitions.xml|presetTextWarpDefinitions.xml');
  process.exit(1);
}
const { window } = new JSDOM('');
const doc = new window.DOMParser().parseFromString(readFileSync(source, 'utf8'), 'application/xml');
const warps = doc.documentElement.localName === 'presetTextWarpDefinitions';
// Numbers as numbers, guide names as strings.
const compact = (v) => (typeof v === 'string' && /^-?\d+$/.test(v) ? Number(v) : v);

/** The range each adjust value may take, from the definition's handles: { adj: [min, max] }. */
function adjustRanges(el) {
  const out = {};
  const handles = [...el.children].find((c) => c.localName === 'ahLst')?.children || [];
  for (const ah of handles) {
    for (const [ref, min, max] of [['gdRefX', 'minX', 'maxX'], ['gdRefY', 'minY', 'maxY'], ['gdRefAng', 'minAng', 'maxAng'], ['gdRefR', 'minR', 'maxR']]) {
      const name = ah.getAttribute(ref);
      const range = [ah.getAttribute(min), ah.getAttribute(max)].map(Number);
      if (name && range.every(Number.isFinite)) out[name] = range;
    }
  }
  return out;
}

const shapes = {};
for (const el of doc.documentElement.children) {
  const def = definitionFromXml(el);
  const ranges = warps ? adjustRanges(el) : {};
  shapes[el.localName] = {
    ...(def.av.length && { av: def.av }),
    ...(Object.keys(ranges).length && { ranges }),
    ...(def.gd.length && { gd: def.gd }),
    ...(def.rect && { rect: def.rect.map(compact) }),
    paths: def.paths.map((p) => ({ ...p, ...(p.w && { w: compact(p.w) }), ...(p.h && { h: compact(p.h) }), cmds: p.cmds.map(([op, ...a]) => [op, ...a.map(compact)]) })),
  };
}
const target = warps ? 'preset-warps.js' : 'preset-shapes.js';
const out = `// Generated by scripts/build-presets.mjs from ${basename(source)} (ECMA-376). Don't edit.
/* eslint-disable */
export default ${JSON.stringify(shapes)};
`;
writeFileSync(new URL(`../src/model/${target}`, import.meta.url), out);
console.log(`${target}: ${Object.keys(shapes).length} ${warps ? 'warps' : 'shapes'}, ${(out.length / 1024).toFixed(0)} KB`);
