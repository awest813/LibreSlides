/**
 * Build src/model/preset-shapes.js, PowerPoint's preset shape geometry, from
 * presetShapeDefinitions.xml (the shape library that comes with the Office
 * Open XML standard, ECMA-376 Part 1; LibreOffice keeps a copy in
 * oox/source/drawingml/customshapes/). Run it when that file changes:
 *
 *   node scripts/build-presets.mjs path/to/presetShapeDefinitions.xml
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { definitionFromXml } from '../src/model/geometry.js';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-presets.mjs presetShapeDefinitions.xml');
  process.exit(1);
}
const { window } = new JSDOM('');
const doc = new window.DOMParser().parseFromString(readFileSync(source, 'utf8'), 'application/xml');
// Numbers as numbers, guide names as strings.
const compact = (v) => (typeof v === 'string' && /^-?\d+$/.test(v) ? Number(v) : v);
const shapes = {};
for (const el of doc.documentElement.children) {
  const def = definitionFromXml(el);
  shapes[el.localName] = {
    ...(def.av.length && { av: def.av }),
    ...(def.gd.length && { gd: def.gd }),
    ...(def.rect && { rect: def.rect.map(compact) }),
    paths: def.paths.map((p) => ({ ...p, ...(p.w && { w: compact(p.w) }), ...(p.h && { h: compact(p.h) }), cmds: p.cmds.map(([op, ...a]) => [op, ...a.map(compact)]) })),
  };
}
const out = `// Generated by scripts/build-presets.mjs from presetShapeDefinitions.xml (ECMA-376). Don't edit.
/* eslint-disable */
export default ${JSON.stringify(shapes)};
`;
writeFileSync(new URL('../src/model/preset-shapes.js', import.meta.url), out);
console.log(`${Object.keys(shapes).length} shapes, ${(out.length / 1024).toFixed(0)} KB`);
